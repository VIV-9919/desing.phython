import turtle
s=turtle.Screen()
s.bgcolor("blue")
pen=turtle.Turtle()
pen.speed(5)
pen.color("red")
pen.width(5)
pen.begin_fill()
pen.fillcolor("red")
pen.left(140)
pen.forward(224)
for _ in range(200):
     pen.right(1)
     pen.circle(-180,1)
pen.left(120)
for _ in range(200):
    pen.right(1)
    pen.circle(-180,1)
pen.forward(224)
pen.end_fill()
pen.up()
pen.goto(0,-50)
pen.down()
pen.color("white")
pen.write("vivekanand",align="center", font=("arial", 25,"bold"))
pen.hideturtle()
turtle.done()